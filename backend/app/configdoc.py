"""Generate docs/reference/configuration.md from the settings models.

Usage: python -m app.configdoc [OUT]
"""

import sys
import types
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel, SecretStr
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from app.core.config import _ENV_PREFIX, _FILE_SECRETS, Settings
from app.rip.settings import RateLimit, RipSettings
from app.runtime.settings import NotifySettings, RuntimeSettings

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUT = "docs/reference/configuration.md"
HEADER = "<!-- generated by app.configdoc; do not edit -->"


def _type_name(t: Any) -> str:
    origin = get_origin(t)
    if origin is Literal:
        return " / ".join(str(a) for a in get_args(t))
    if origin in (Union, types.UnionType):
        parts = [a for a in get_args(t) if a is not type(None)]
        return " or ".join(_type_name(a) for a in parts) + " (optional)"
    if origin is not None:
        return f"{origin.__name__}[{', '.join(_type_name(a) for a in get_args(t))}]"
    return getattr(t, "__name__", str(t))


def _is_secret(t: Any) -> bool:
    return t is SecretStr or (
        get_origin(t) in (Union, types.UnionType) and SecretStr in get_args(t)
    )


def _default(name: str, f: FieldInfo) -> str:
    if f.default is PydanticUndefined:
        return "required"
    if f.default is None or _is_secret(f.annotation):
        return "unset"
    if isinstance(f.default, bool):
        return f"`{str(f.default).lower()}`"
    if isinstance(f.default, (list, dict)):
        return f"`{f.default!r}`".replace("'", '"')
    return f"`{f.default}`"


def _constraints(f: FieldInfo) -> str:
    out = []
    for m in f.metadata:
        for attr, sym in (("ge", ">="), ("le", "<="), ("gt", ">"), ("lt", "<")):
            v = getattr(m, attr, None)
            if v is not None:
                out.append(f"{sym} {v}")
    return ", ".join(out) or "-"


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def _model_table(
    title: str, intro: str, model: type[BaseModel], fields: dict[str, FieldInfo] | None = None
) -> list[str]:
    lines = [
        f"## {title}",
        "",
        intro,
        "",
        "| Key | Type | Default | Constraints | Description |",
        "|---|---|---|---|---|",
    ]
    for name, f in (fields or model.model_fields).items():
        lines.append(
            f"| `{name}` | {_cell(_type_name(f.annotation))} | {_default(name, f)} "
            f"| {_constraints(f)} | {_cell(f.description or '')} |"
        )
    return lines + [""]


def render() -> str:
    lines = [
        HEADER,
        "",
        "# Configuration reference",
        "",
        "## Environment variables",
        "",
        "| Env var | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for name, f in Settings.model_fields.items():
        var = f"{_ENV_PREFIX}{name.upper()}"
        lines.append(
            f"| `{var}` | {_cell(_type_name(f.annotation))} | {_default(name, f)} "
            f"| {_cell(f.description or '')} |"
        )
        if name in _FILE_SECRETS:
            lines.append(
                f"| `{var}_FILE` | path | unset | Path to a file holding the value of `{var}` "
                f"(Docker secrets); used when `{var}` is unset. |"
            )
    lines.append(
        "| `FORWARDED_ALLOW_IPS` | str | `127.0.0.1` | Comma-separated proxy addresses uvicorn "
        "trusts for `X-Forwarded-*` headers (set to the reverse proxy's address). |"
    )
    lines.append("")
    lines += _model_table(
        "Rip settings (admin, GUI/API)",
        "Stored in the database and edited by an admin in the web UI or API (settings key `rip`).",
        RipSettings,
    )
    lines += _model_table(
        "Rate limit entry",
        "Value type of each `rate_limits` entry.",
        RateLimit,
    )
    lines += _model_table(
        "Runtime settings",
        "Stored in the database and edited by an admin (settings key `runtime`).",
        RuntimeSettings,
    )
    lines += _model_table(
        "Notification settings",
        "Stored in the database and edited by an admin (settings key `notify`).",
        NotifySettings,
    )
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str]) -> None:
    out = Path(argv[0]) if argv else Path(DEFAULT_OUT)
    if not out.is_absolute():
        out = REPO / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render())


if __name__ == "__main__":
    main(sys.argv[1:])
